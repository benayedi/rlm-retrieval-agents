"""Build the documents of the follow-up studies from two files only, so they cannot drift from the evidence:

  experiments/registry.yaml (section follow_up_studies)   facts: design, model, budgets, dates, launcher, config, control
  results/follow_up/numbers.yaml                          every reported number, with its judge and its source

Writes:
  results/follow_up/studies.md                    one table per study (numbers + named source)
  docs/experiments/<study>/<ID>.md                one document per study ID
  docs/experiments/FOLLOW_UP_STUDIES.md           the overview, from scripts/docs/FOLLOW_UP_STUDIES.template.md
                                                  ({{RESULT:<ID>}} -> that study's table, {{INDEX}} -> the index)

usage: python scripts/docs/make_follow_up_docs.py
"""
from pathlib import Path

import yaml

from naming import paper_names

ROOT = Path(__file__).resolve().parents[2]
REG = yaml.safe_load((ROOT / "experiments/registry.yaml").read_text())
FU = REG["follow_up_studies"]
NUM = yaml.safe_load((ROOT / "results/follow_up/numbers.yaml").read_text())
DIRS = {"SP": "search_policy", "GEPA": "prompt_optimisation", "VAR": "run_variation", "ERR": "error_analysis",
        "FB": "frames_baselines", "DSA": "dspy_rlm", "FRC": "document_repl", "TWQ-1": "snippet_repl",
        "TWQ-2": "document_repl"}
SOURCES = """Sources: **EVIDENCE** = the thesis evidence ledger, section "RQ4: GPT-4.1 re-judge"; **STATUS**, **GEPA_PLAN**,
**BENCHMARKS**, **HANDOFF** = `docs/EXPERIMENTS_STATUS.md`, `docs/GEPA_BROWSECOMP_PLAN.md`, `docs/DATASET_BENCHMARKS.md`,
`docs/HANDOFF.md` of the original repository; **SUMMARY_XLSX** = its `docs/rlm_results_summary.xlsx`; **VERDICTS** =
[`results/follow_up/verdicts/`](verdicts/) of this repository. Numbers are copied, not recomputed."""


def folder(i):
    return DIRS.get(i) or DIRS[i.split("-")[0]]


def doc_path(i):
    return ROOT / "docs/experiments" / folder(i) / f"{i}.md"


def rel(target, frm):
    import os
    return os.path.relpath(ROOT / target, (ROOT / frm).parent).replace(os.sep, "/")


def table(i):
    rows = NUM[i]["rows"]
    out = ["| Measure | This run | Compared with | n | Test / note | Judge | Source |", "|---|---|---|---|---|---|---|"]
    for r in rows:
        cells = [r["measure"], r["arm"], r.get("control", ""), str(r.get("n", "")), r.get("test", ""), r["judge"], r["source"]]
        out.append("| " + " | ".join(str(c).replace("|", "/") for c in cells) + " |")
    return "\n".join(out)


def entry(i):
    return next(e for e in FU if e["id"] == i)


def fmt(v):
    if isinstance(v, dict):
        return "; ".join(f"{k}: {x}" for k, x in v.items())
    if isinstance(v, list):
        return "; ".join(f"`{x}`" if "/" in str(x) else str(x) for x in v)
    return str(v)


def write_doc(e):
    i, p = e["id"], doc_path(e["id"])
    reported = e.get("reported", "")
    head = [f"# {i}: {NUM[i]['title']}", "",
            f"Generated by `scripts/docs/make_follow_up_docs.py` from [`registry.yaml`]({rel('experiments/registry.yaml', p.relative_to(ROOT))}) "
            f"(section `follow_up_studies`) and [`numbers.yaml`]({rel('results/follow_up/numbers.yaml', p.relative_to(ROOT))}). "
            f"Overview of all follow-up studies: [FOLLOW_UP_STUDIES.md]({rel('docs/experiments/FOLLOW_UP_STUDIES.md', p.relative_to(ROOT))}).", "",
            f"**Question.** {e['question']}", ""]
    facts = [("Study", e.get("study")), ("Agent", e.get("agent")), ("Benchmark", e.get("benchmark")), ("Model", e.get("model")),
             ("Effort requested / sent", f"{e['effort_requested']} / {e['effort_sent']}" if "effort_requested" in e else None),
             ("Retrieval", e.get("retriever")), ("Budgets", fmt(e["budgets"]) if "budgets" in e else None),
             ("Run", e.get("run_name")), ("Dates", e.get("dates")), ("Control", e.get("control")),
             ("Judge (reported numbers)", e.get("judge")), ("Superseded judge", e.get("superseded_judge")),
             ("Launcher", e.get("launcher")), ("Driver", e.get("driver")), ("Config", e.get("config")),
             ("Verdicts", e.get("verdicts")), ("Candidates", e.get("candidates")), ("Results", e.get("results")),
             ("Records", e.get("trajectories")), ("Original outputs", fmt(e["original_outputs"]) if "original_outputs" in e else None),
             ("Reported", reported if reported is not True else "yes")]
    body = ["## Configuration", "", "| | |", "|---|---|"] + [f"| {k} | {str(v).replace('|', '/')} |" for k, v in facts if v not in (None, "")]
    body += ["", "## Results", "", table(i), ""]
    if e.get("notes"):
        body += ["## Caveats", ""] + [f"- {n}" for n in e["notes"]] + [""]
    body += ["Issues found in the code of this study are listed in the study's `CHANGES_FROM_ORIGINAL.md` and in "
             f"[KNOWN_ISSUES.md]({rel('docs/verification/KNOWN_ISSUES.md', p.relative_to(ROOT))}).", ""]
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(paper_names("\n".join(head + body)))


def main():
    for e in FU:
        write_doc(e)
    # results/follow_up/studies.md
    out = ["# Follow-up studies: numbers", "",
           "Generated by `scripts/docs/make_follow_up_docs.py` from [`numbers.yaml`](numbers.yaml). One table per study ID; every "
           "number is copied from the source named in its row. Only gpt-4.1 accuracies are reported; Qwen3.6-judged values are kept "
           "as \"superseded\" or \"Qwen3.6 only\" and must not be cited as results.", "", SOURCES, ""]
    for i in NUM:
        out += [f"## {i}: {NUM[i]['title']}", "", table(i), "", f"Document: [{i}]({rel(str(doc_path(i).relative_to(ROOT)), 'results/follow_up/studies.md')})", ""]
    (ROOT / "results/follow_up/studies.md").write_text(paper_names("\n".join(out)))
    # overview from the template
    tpl = (ROOT / "scripts/docs/FOLLOW_UP_STUDIES.template.md").read_text()
    idx = ["| ID | Study | Question | Control | Judge | Document |", "|---|---|---|---|---|---|"]
    for e in FU:
        d = doc_path(e["id"]).relative_to(ROOT / "docs/experiments")
        idx.append(f"| {e['id']} | {e['study']} | {e['question'].split(':')[0] if e['question'].startswith('RQ4') else e['question'][:90]} | "
                   f"{e.get('control', '—')} | {e.get('judge', '—')} | [doc]({d.as_posix()}) |")
    tpl = tpl.replace("{{INDEX}}", "\n".join(idx)).replace("{{SOURCES}}", SOURCES.replace("](verdicts/)", "](../../results/follow_up/verdicts/)"))
    for i in NUM:
        tpl = tpl.replace("{{RESULT:%s}}" % i, table(i))
    assert "{{" not in tpl, "unfilled placeholder in FOLLOW_UP_STUDIES.template.md"
    (ROOT / "docs/experiments/FOLLOW_UP_STUDIES.md").write_text(paper_names(tpl))
    print(f"{len(FU)} documents, studies.md, FOLLOW_UP_STUDIES.md")


if __name__ == "__main__":
    main()
